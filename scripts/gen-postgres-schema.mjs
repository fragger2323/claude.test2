#!/usr/bin/env node
// Generates prisma/postgres/schema.prisma from prisma/schema.prisma (SQLite dev schema)
// and (re)creates the PostgreSQL baseline migration. The schema is portable by design
// (no native enums, Json columns, no raw SQL), so only the datasource provider changes.
import { readFileSync, writeFileSync, mkdirSync, existsSync, readdirSync } from 'node:fs';
import { execFileSync } from 'node:child_process';
import { join } from 'node:path';

const src = readFileSync('prisma/schema.prisma', 'utf8');
const header = '// GENERATED by scripts/gen-postgres-schema.mjs from prisma/schema.prisma — do not edit by hand.\n';
const pg = header + src
  .replace(/provider\s*=\s*"sqlite"/, 'provider = "postgresql"');
// NOTE: the client is generated to the default location, so `@prisma/client` becomes the
// PostgreSQL client in production builds (`npm run db:pg:generate`). Model APIs are identical.

mkdirSync('prisma/postgres/migrations', { recursive: true });
writeFileSync('prisma/postgres/schema.prisma', pg);
writeFileSync('prisma/postgres/migrations/migration_lock.toml', 'provider = "postgresql"\n');

const migrationsDir = 'prisma/postgres/migrations';
const existing = readdirSync(migrationsDir).filter((d) => /^\d+_/.test(d));
if (existing.length === 0 || process.argv.includes('--baseline')) {
  const sql = execFileSync('npx', ['prisma', 'migrate', 'diff', '--from-empty', '--to-schema-datamodel', 'prisma/postgres/schema.prisma', '--script'], { encoding: 'utf8' });
  const dir = join(migrationsDir, '00000000000000_init');
  if (!existsSync(dir)) mkdirSync(dir);
  writeFileSync(join(dir, 'migration.sql'), sql);
  console.log('PostgreSQL baseline migration written to', dir);
} else {
  console.log('PostgreSQL migrations already exist. For schema changes run against a PG database:');
  console.log('  npx prisma migrate dev --schema prisma/postgres/schema.prisma --name <change>');
}
console.log('Wrote prisma/postgres/schema.prisma');
